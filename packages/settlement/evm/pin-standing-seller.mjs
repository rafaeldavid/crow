// Writes standing-seller-code.ts from `forge build` output: the seller contract's creation code, which the node pins so
// a live chain needs no contracts/out (ADR-0040 §4). A new pin moves every seller contract's address.
//
// Pin from a clean checkout with CI's submodules only (the anvil job in .github/workflows/ci.yml): forge adds a
// remapping for every library it finds under contracts/lib, the remappings go into the metadata hash at the end of
// the code, and a checkout with more submodules builds the same code with another hash (measured on 2026-11-25:
// 21 remappings on a working Mac, 20 in CI). `standing-seller.test.ts` compares the code without that hash.
//   node packages/settlement/evm/pin-standing-seller.mjs [<contracts/out of the clean checkout>]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = import.meta.dirname;
const out = process.argv[2] ?? join(here, '..', '..', '..', 'contracts', 'out');
const artifact = JSON.parse(readFileSync(join(out, 'HoldbackStandingSeller.sol', 'HoldbackStandingSeller.json'), 'utf8'));
const code = artifact.bytecode.object;
if (!/^0x([0-9a-f]{2})+$/.test(code)) throw new Error('the artifact has no creation code');
const lines = [
  '// Generated by pin-standing-seller.mjs from a clean checkout\'s forge build of contracts/src/HoldbackStandingSeller.sol,',
  '// with CI\'s submodules. Do not edit: a changed byte moves every standing seller\'s CREATE2 address.',
  '// standing-seller.test.ts checks it against the build, without the metadata hash at its end.',
  "import type { Hex } from 'viem';",
  '',
  '/** HoldbackStandingSeller\'s creation code, without the constructor argument. */',
  `export const STANDING_SELLER_CREATION_CODE: Hex = '${code}';`,
  '',
];
writeFileSync(join(here, 'standing-seller-code.ts'), lines.join('\n'));
console.log(`pinned ${(code.length - 2) / 2} bytes of creation code`);
