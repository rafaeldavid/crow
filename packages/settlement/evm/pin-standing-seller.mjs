// Writes standing-seller-code.ts from `forge build` output: the seller contract's creation code, which the node pins so
// a live chain needs no contracts/out (ADR-0040 §4). Run after a change to contracts/src/HoldbackStandingSeller.sol:
//   (cd contracts && forge build) && node packages/settlement/evm/pin-standing-seller.mjs
// standing-seller.test.ts fails while the pin and the build differ. A new pin moves every seller contract's address.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = import.meta.dirname;
const artifact = JSON.parse(readFileSync(join(here, '..', '..', '..', 'contracts', 'out', 'HoldbackStandingSeller.sol', 'HoldbackStandingSeller.json'), 'utf8'));
const code = artifact.bytecode.object;
if (!/^0x([0-9a-f]{2})+$/.test(code)) throw new Error('the artifact has no creation code');
const lines = [
  '// Generated by pin-standing-seller.mjs from contracts/out (forge build of contracts/src/HoldbackStandingSeller.sol).',
  '// Do not edit: a changed byte moves every standing seller\'s CREATE2 address. standing-seller.test.ts checks it against the build.',
  "import type { Hex } from 'viem';",
  '',
  '/** HoldbackStandingSeller\'s creation code, without the constructor argument. */',
  `export const STANDING_SELLER_CREATION_CODE: Hex = '${code}';`,
  '',
];
writeFileSync(join(here, 'standing-seller-code.ts'), lines.join('\n'));
console.log(`pinned ${(code.length - 2) / 2} bytes of creation code`);
